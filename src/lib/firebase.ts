/**
 * Ensures player is authenticated via Firebase Anonymous Auth
 */
export async function ensureAnonymousAuth(): Promise<FirebaseUser | null> {
  if (auth.currentUser) {
    return auth.currentUser;
  }
  if (typeof window !== 'undefined' && (window as any).__QUIZARENA_E2E_TEST__) {
    const anonUser = createMockUser({
      uid: `anon_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      isAnonymous: true,
      email: null,
      emailVerified: false,
    });
    try {
      Object.defineProperty(auth, 'currentUser', {
        get: () => anonUser,
        set: () => {},
        configurable: true,
      });
    } catch {}
    return anonUser;
  }
  try {
    const cred = await signInAnonymously(auth);
    return cred.user;
  } catch (error) {
    console.warn('Anonymous auth sign-in warning:', error);
    return null;
  }
}

